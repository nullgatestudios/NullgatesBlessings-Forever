"""Builds Data/Blessings.lua from the Forever client's tables on wago.tools.

The paladin's blessings (single and Greater, every trainer rank with the level it's learned at and its
duration, and the Greater blessings' reagent) and auras (every rank). Blessing of Salvation is called
"Salvation" in Forever and its Greater form "Mass Salvation"; Blessing of Sanctuary doesn't exist.
Also Oath of Light, Forever's Holy talent (one ally at a time; no trainer level).

Usage:
  python tools/generate_blessing_data.py [--build 1.60.1.70532] [--data DIR]
"""
import argparse
import csv
import io
import json
import os
import sys
import urllib.request
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "NullgatesBlessings-Forever", "Data", "Blessings.lua")
TABLES = ("SpellName", "SpellLevels", "SpellMisc", "SpellDuration", "SpellReagents", "SkillLineAbility")
PALADIN_LINES = {"594", "267", "184"}
BLESSINGS = [  # key, single, greater
    ("might", "Blessing of Might", "Greater Blessing of Might"),
    ("wisdom", "Blessing of Wisdom", "Greater Blessing of Wisdom"),
    ("kings", "Blessing of Kings", "Greater Blessing of Kings"),
    ("light", "Blessing of Light", "Greater Blessing of Light"),
    ("salvation", "Salvation", "Mass Salvation"),
]
AURAS = [("devotion", "Devotion Aura"), ("retribution", "Retribution Aura"), ("concentration", "Concentration Aura"),
         ("shadow", "Shadow Resistance Aura"), ("frost", "Frost Resistance Aura"), ("fire", "Fire Resistance Aura")]


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "NullgatesBlessings-generator"})
    with urllib.request.urlopen(req, timeout=300) as resp:
        return resp.read().decode("utf-8")


def latest_build():
    return json.loads(fetch("https://wago.tools/api/builds/latest"))["wow_classic_beta"]["version"]


def load(name, build, data_dir):
    if data_dir:
        with open(os.path.join(data_dir, name + ".csv"), encoding="utf-8") as f:
            text = f.read()
    else:
        text = fetch("https://wago.tools/db2/%s/csv?build=%s" % (name, build))
    return list(csv.DictReader(io.StringIO(text)))


def to_int(value):
    try:
        return int(float(value))
    except (TypeError, ValueError):
        return 0


def build(t):
    names = {r["ID"]: r["Name_lang"] for r in t["SpellName"]}
    levels = {r["SpellID"]: to_int(r.get("SpellLevel")) or to_int(r.get("BaseLevel")) for r in t["SpellLevels"]}
    misc = {r["SpellID"]: r for r in t["SpellMisc"]}
    durations = {r["ID"]: to_int(r["Duration"]) for r in t["SpellDuration"]}
    reagents = {r["SpellID"]: to_int(r.get("Reagent_0")) for r in t["SpellReagents"]}
    by_name = defaultdict(set)
    for r in t["SkillLineAbility"]:
        if r["SkillLine"] in PALADIN_LINES and levels.get(r["Spell"]):
            by_name[names.get(r["Spell"], "")].add(r["Spell"])

    def ranks(name):
        out = []
        for spell in sorted(by_name.get(name, []), key=lambda s: levels[s]):
            m = misc.get(spell)
            out.append((to_int(spell), levels[spell], durations.get(m["DurationIndex"], 0) // 1000 if m else 0))
        return out

    blessings = []
    for key, single, greater in BLESSINGS:
        s, g = ranks(single), ranks(greater)
        if not s:
            print("not in this build:", single)  # Blessing of Light was removed in 1.60.1.71037
            continue
        blessings.append({"key": key, "single": s, "greater": g, "reagent": reagents.get(str(g[0][0]), 0) if g else 0,
                          "name": single})
    oath = None
    for r in t["SkillLineAbility"]:
        if r["SkillLine"] in PALADIN_LINES and names.get(r["Spell"]) == "Oath of Light":
            m = misc.get(r["Spell"])
            oath = (to_int(r["Spell"]), durations.get(m["DurationIndex"], 0) // 1000 if m else 0)
    auras = []
    for key, name in AURAS:
        r = ranks(name)
        if r:
            auras.append({"key": key, "ranks": r, "name": name})
    return blessings, auras, oath


def write(build_id, blessings, auras, oath):
    def fmt(lst):
        return ", ".join("{ %d, %d, %d }" % x for x in lst)
    lines = [
        "-- Generated by tools/generate_blessing_data.py from the Forever client data. Do not edit by hand.",
        "local _, ns = ...",
        "",
        'ns.BLESSING_DATA_BUILD = "%s"' % build_id,
        "",
        "-- Blessings: single and Greater ranks ({ spell ID, level learned, duration in seconds }) and the",
        "-- Greater blessings' reagent.",
        "ns.BLESSINGS = {",
    ]
    for b in blessings:
        lines.append('    { key = "%s", single = { %s }, greater = { %s }, reagent = %d }, -- %s' % (
            b["key"], fmt(b["single"]), fmt(b["greater"]), b["reagent"], b["name"]))
    lines += ["}", "", "-- Auras: every rank ({ spell ID, level learned, duration }).", "ns.AURAS = {"]
    for a in auras:
        lines.append('    { key = "%s", ranks = { %s } }, -- %s' % (a["key"], fmt(a["ranks"]), a["name"]))
    lines.append("}")
    if oath:
        lines += ["", "-- Oath of Light (Holy talent): { spell ID, duration in seconds }.",
                  "ns.OATH_OF_LIGHT = { %d, %d }" % oath]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--build")
    parser.add_argument("--data")
    args = parser.parse_args()
    build_id = args.build or latest_build()
    blessings, auras, oath = build({name: load(name, build_id, args.data) for name in TABLES})
    write(build_id, blessings, auras, oath)
    for b in blessings:
        print("%-10s %d single (%ds), %d greater (%ds), reagent %d" % (b["key"], len(b["single"]), b["single"][-1][2],
              len(b["greater"]), b["greater"][-1][2] if b["greater"] else 0, b["reagent"]))
    print("auras:", ", ".join(a["key"] for a in auras))
    print("oath of light:", oath)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
